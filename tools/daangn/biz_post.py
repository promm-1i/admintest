def photo_count(pg) -> int:
    """사진 칸의 'n/10' 표시. 붙이고 나면 클래스가 바뀌어서 글자로 찾는다."""
    loc = pg.locator("text=/^\d+\/10$/")
    if not loc.count():
        return -1
    return int(loc.first.inner_text().split("/")[0])


def close_dialogs(pg) -> None:
    """열려 있는 대화창을 닫는다. 덮개(backdrop)가 남으면 클릭이 전부 막힌다."""
    for _ in range(6):
        if pg.evaluate("document.querySelectorAll('[class*=seed-dialog__backdrop]').length") == 0:
            return
        # 임시 저장된 글이 있으면 '새로 쓰기'로 비우고 시작한다
        done = False
        for name in ("새로 쓰기", "닫기", "확인"):
            btn = pg.get_by_role("button", name=name)
            if btn.count():
                try:
                    btn.first.click(timeout=3000)
                    done = True
                    break
                except Exception:
                    pass
        if not done:
            try:
                pg.keyboard.press("Escape")
            except Exception:
                pass
        pg.wait_for_timeout(700)
    n = pg.evaluate("document.querySelectorAll('[class*=seed-dialog__backdrop]').length")
    if n:
        print(f"  (덮개 {n}개가 안 닫힘 — 화면을 확인해야 함)")


# 흰 바탕에 글자만 있는 설명 카드 — 피드에서 빈 블록으로 보인다(담화재 글이 이것 때문에 지워졌다)
TEXT_ONLY = ("02_", "06_", "09_")
ORDER = ("01_", "04_", "05_", "07_")


def pics(folder: str, limit: int = 10) -> list[Path]:
    """실제 화면이 담긴 것만. 00_전체_* 는 세로 2만 px 이 넘고, 02·06·09 는 글자만이라 뺀다."""
    d = CAP / folder
    keep = [f for f in sorted(d.glob("*.jpg"))
            if not f.name.startswith("00_") and not f.name.startswith(TEXT_ONLY)]
    head = [f for f in keep if f.name.startswith(("01_", "04_"))]
    mid = [f for f in keep if f.name.startswith("05_")]
    tail = [f for f in keep if f.name.startswith("07_")]   # 모바일 화면은 자리를 비워 둔다
    return head + mid[:max(0, limit - len(head) - len(tail))] + tail


